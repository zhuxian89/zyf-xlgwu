export function generateMathProblems(count: number = 5): MathProblem[] {
    const problems: MathProblem[] = [];

    for (let i = 0; i < count; i++) {
        const typeRoll = Math.random();

        if (typeRoll < 0.3) {
            // Multiplication (1-9)
            const a = Math.floor(Math.random() * 9) + 1;
            const b = Math.floor(Math.random() * 9) + 1;
            problems.push({
                id: `m${Date.now()}${i}`,
                question: `${a} × ${b} = ?`,
                answer: a * b,
                type: 'mul'
            });
        } else if (typeRoll < 0.5) {
            // Division (Simple)
            const b = Math.floor(Math.random() * 9) + 1;
            const ans = Math.floor(Math.random() * 9) + 1;
            const a = b * ans;
            problems.push({
                id: `d${Date.now()}${i}`,
                question: `${a} ÷ ${b} = ?`,
                answer: ans,
                type: 'div'
            });
        } else {
            // Advanced Thinking Word Problems
            const templates = [
                // Age Problem
                {
                    gen: () => {
                        const diff = Math.floor(Math.random() * 5) + 3; // 3-7 years diff
                        const base = Math.floor(Math.random() * 5) + 5; // 5-9 years old
                        const future = Math.floor(Math.random() * 5) + 3; // 3-7 years later
                        return {
                            q: `小红今年${base}岁，姐姐比她大${diff}岁。${future}年后，姐姐比小红大几岁？`,
                            a: diff
                        };
                    }
                },
                // Planting Trees (Intervals)
                {
                    gen: () => {
                        const interval = Math.floor(Math.random() * 3) + 2; // 2-4m
                        const count = Math.floor(Math.random() * 4) + 3; // 3-6 trees
                        const total = (count - 1) * interval;
                        return {
                            q: `在一条长${total}米的小路一边植树，每隔${interval}米种一棵（两端都种），一共要种多少棵？`,
                            a: count
                        };
                    }
                },
                // Queue Problem
                {
                    gen: () => {
                        const front = Math.floor(Math.random() * 5) + 3;
                        const back = Math.floor(Math.random() * 5) + 3;
                        return {
                            q: `同学们排队做操，小明前面有${front}个人，后面有${back}个人，这一排一共有多少人？`,
                            a: front + back + 1
                        };
                    }
                },
                // Chicken and Rabbit (Simplified)
                {
                    gen: () => {
                        // Ensure integer solution: 2x + 4y = legs, x + y = heads
                        // Let rabbits = r (1-3), chickens = c (2-5)
                        const r = Math.floor(Math.random() * 3) + 1;
                        const c = Math.floor(Math.random() * 4) + 2;
                        const heads = r + c;
                        const legs = c * 2 + r * 4;
                        return {
                            q: `笼子里有鸡和兔，从上面数有${heads}个头，从下面数有${legs}只脚。问兔子有几只？`,
                            a: r
                        };
                    }
                },
                // Sawing Wood (Intervals)
                {
                    gen: () => {
                        const times = Math.floor(Math.random() * 3) + 2; // 2-4 cuts
                        const timePerCut = Math.floor(Math.random() * 3) + 2; // 2-4 mins
                        const segments = times + 1;
                        return {
                            q: `把一根木头锯成${segments}段，每锯一次要${timePerCut}分钟，一共要花多少分钟？`,
                            a: times * timePerCut
                        };
                    }
                },
                // Equivalent Substitution
                {
                    gen: () => {
                        const val1 = Math.floor(Math.random() * 2) + 2; // 2-3
                        const val2 = Math.floor(Math.random() * 2) + 2; // 2-3
                        // 1 A = val1 B, 1 B = val2 C. 1 A = ? C
                        return {
                            q: `1支钢笔可以换${val1}支圆珠笔，1支圆珠笔可以换${val2}支铅笔，1支钢笔可以换几支铅笔？`,
                            a: val1 * val2
                        };
                    }
                }
            ];

            const t = templates[Math.floor(Math.random() * templates.length)];
            const problem = t.gen();

            problems.push({
                id: `w${Date.now()}${i}`,
                question: problem.q,
                answer: problem.a,
                type: 'word'
            });
        }
    }

    return problems;
}
